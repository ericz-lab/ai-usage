/**
 * `bun scripts/pack.ts [--out DIR]`: this app as an ai-space installation package (`.spaceapp`,
 * ai-space docs/app-packages.md), built from the source tree without changing it.
 *
 * The source manifest stays spec 1 for the git deployment. The package gets a spec-2 manifest made
 * from it here: `service`, `url`, `deploy` and `repo` go, `version` comes from package.json, and
 * a blob store that must be S3 may fall back to files, and `launch` starts `launch.ts`, a generated entry that applies the literal values of `service.env`
 * as defaults, records the port ai-space assigned in `<data dir>/service.port` (the app's own
 * command-line tools read it) and then runs the service's entry as its child.
 *
 * What goes in and how it runs is `spacePackage` in package.json:
 *   include  files and directories of the release (tests are left out)
 *   mode     on-demand (stopped when idle) or background (kept running)
 *   offline  { features, online }: what works without the internet and what needs it
 *
 * The packer is ai-space's own `space app pack`: SPACE_CLI (the `space` binary or ai-space's
 * src/index.ts), else `space` on PATH, else the Local edition's installed release.
 */
import { cp, mkdir, mkdtemp, readdir, rm } from "node:fs/promises";
import { homedir, tmpdir } from "node:os";
import { join, resolve } from "node:path";

type PackageConfig = { include: string[]; mode: "on-demand" | "background"; offline: { features: string[]; online: string[] } };
type SourceManifest = Record<string, unknown> & { name: string; service?: { command?: string; health?: string; env?: Record<string, unknown> } };

const root = resolve(import.meta.dir, "..");
const args = Bun.argv.slice(2);
const outAt = args.indexOf("--out");
const outDir = resolve(outAt >= 0 && args[outAt + 1] ? args[outAt + 1]! : join(tmpdir(), "space-packages"));

const pkg = (await Bun.file(join(root, "package.json")).json()) as { version?: string; spacePackage?: PackageConfig };
const config = pkg.spacePackage;
if (!config?.include?.length) throw new Error("package.json: spacePackage.include is missing");
if (!pkg.version || !/^\d+\.\d+\.\d+$/.test(pkg.version)) throw new Error("package.json: version must be major.minor.patch");

const source = Bun.YAML.parse(await Bun.file(join(root, "space.yaml")).text()) as SourceManifest;
const { service, url: _url, deploy: _deploy, repo: _repo, spec: _spec, ...components } = source;
const entry = /^bun\s+(\S+)$/.exec(service?.command ?? "")?.[1];
if (!entry || !service?.health) throw new Error("space.yaml: service.command must be `bun <entry>` and service.health must be set");

// A package installs on machines without an object store too: there the pictures and files go to the data directory.
const storage = components.storage as { blobs?: unknown } | undefined;
if (storage?.blobs === "s3") storage.blobs = { backend: "s3", fallback: "file" };

/** The release manifest: the source manifest's components under spec 2, with a launch in place of the service. */
const manifest = {
  ...components,
  spec: 2,
  version: pkg.version,
  requires: { spaceApi: 1, bun: "1.3.0" },
  offline: config.offline,
  launch: { kind: "process", runtime: "bun", entry: "launch.ts", mode: config.mode, ...(config.mode === "on-demand" ? { idleTimeoutMs: 300_000 } : {}), health: service.health },
};

// `${VAR}` values are the workspace's to give (data/<app>/.env on a package install); only literals become defaults.
const defaults = Object.entries(service.env ?? {}).filter(([, v]) => !String(v).includes("${")).map(([k, v]) => [k, String(v)] as const);
const launcher = `// Generated by scripts/pack.ts: the package's entry. The service runs as a child so that it is the
// main module, as under the git deployment; signals pass through and its exit code is this one's.
const defaults: Record<string, string> = ${JSON.stringify(Object.fromEntries(defaults))};
const dataDir = process.env.SPACE_APP_DATA_DIR, port = process.env.PORT;
if (dataDir && port) await Bun.write(dataDir + "/service.port", port);
const child = Bun.spawn([process.execPath, ${JSON.stringify(entry)}], { cwd: import.meta.dir, env: { ...defaults, ...process.env }, stdin: "ignore", stdout: "inherit", stderr: "inherit" });
for (const signal of ["SIGTERM", "SIGINT", "SIGHUP"] as const) process.on(signal, () => child.kill(signal));
process.exit(await child.exited);
`;

const stage = await mkdtemp(join(tmpdir(), `${source.name}-pack-`));
try {
  for (const item of config.include) {
    await cp(join(root, item), join(stage, item), { recursive: true, filter: (from) => !/\.test\.tsx?$/.test(from) });
  }
  await Bun.write(join(stage, "launch.ts"), launcher);
  await Bun.write(join(stage, "space.yaml"), Bun.YAML.stringify(manifest, null, 2));

  const output = join(outDir, `${source.name}-${pkg.version}.spaceapp`);
  await mkdir(outDir, { recursive: true });
  await rm(output, { force: true });
  const include = (await readdir(stage)).filter((name) => name !== "space.yaml").sort().join(",");
  const cli = await spaceCli();
  await run([...cli, "app", "pack", stage, "--include", include, "--source-included", "--output", output]);
  await run([...cli, "app", "inspect-package", output]);
  console.log(output);
} finally {
  await rm(stage, { recursive: true, force: true });
}

async function spaceCli(): Promise<string[]> {
  const asCommand = (path: string) => (path.endsWith(".ts") ? [process.execPath, path] : [path]);
  if (process.env.SPACE_CLI) return asCommand(process.env.SPACE_CLI);
  const onPath = Bun.which("space");
  if (onPath) return [onPath];
  for (const release of [join(homedir(), "Library/Application Support/ai-space/local/current"), join(homedir(), ".local/share/ai-space/local/current")]) {
    const index = join(release, "src/index.ts");
    if (await Bun.file(index).exists()) return asCommand(index);
  }
  throw new Error("ai-space's CLI was not found: set SPACE_CLI to the `space` binary or to ai-space's src/index.ts");
}

async function run(cmd: string[]): Promise<void> {
  const proc = Bun.spawn(cmd, { stdin: "ignore", stdout: "inherit", stderr: "inherit" });
  if ((await proc.exited) !== 0) throw new Error(`${cmd.slice(-4).join(" ")}: failed`);
}
